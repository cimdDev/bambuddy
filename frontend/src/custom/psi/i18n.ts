export const PSI_TRANSLATIONS: Record<'en' | 'de' | 'fr' | 'it', Tree> = { en, de, fr, it };

let registered = false;

/** Merge the PSI keys under `psi.*`. Idempotent; runs on import. */
export function registerPsiTranslations(): void {
  if (registered) return;
  registered = true;
  for (const [lng, tree] of Object.entries(PSI_TRANSLATIONS)) {
    i18n.addResourceBundle(lng, 'translation', { psi: tree }, true, false);
  }
}

registerPsiTranslations();
